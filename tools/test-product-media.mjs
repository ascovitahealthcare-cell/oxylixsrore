import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../scripts/store-core.js', import.meta.url), 'utf8');
const merge = source.slice(source.indexOf('function mergeBackendProducts('), source.indexOf('// ═', source.indexOf('function mergeBackendProducts(')));
const products = [{id:1,image:'https://old.example/stale.webp'}];
const ctx = vm.createContext({PRODUCTS:products,updateSaleUIVisibility(){},syncProductStructuredData(){},mediaTypeFromUrl:u=>/\.mp4$/.test(u)?'video':'image'});
vm.runInContext(merge,ctx);
ctx.mergeBackendProducts([{id:1,media:[{url:'https://example.com/new.webp'}]},{id:2,media:'[{"url":"https://example.com/media.webp"}]'},{id:3,images:[{url:'/cdn-storage/product-images/photo.webp'}]},{id:4,media:'null',images:'{}',image:'https://example.com/legacy.webp'},{id:5,images:['https://example.com/string.webp']},{id:6,media:[null,{},7],image:'https://example.com/valid.webp'}]);
assert.equal(products[0].image,'https://example.com/new.webp');
assert.equal(products[1].image,'https://example.com/media.webp');
assert.equal(products[2].image,'/cdn-storage/product-images/photo.webp');
assert.equal(products[3].image,'https://example.com/legacy.webp');
assert.equal(products[4].image,'https://example.com/string.webp');
assert.equal(products[5].image,'https://example.com/valid.webp');
ctx.mergeBackendProducts([{id:1,price:99}]);
assert.equal(products[0].image,'https://example.com/new.webp');
assert.equal(products[0].price,99);
console.log('Product media regression tests passed');
